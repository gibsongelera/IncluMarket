-- InclusiveMarket — tables behind the buyer, seller and admin features.
--
--   im_addresses            saved delivery addresses (checkout, account)
--   im_product_reviews      + review moderation, seller reply, link to the
--                             order line that earned it
--   im_notifications        + new types; im_notification_prefs per type
--   im_product_views        what a signed-in buyer looked at, for
--                             "Recommended for you" (kept 90 days; opt-out)
--   im_banners              homepage banners (admin merchandising)
--   im_profiles             + shop profile fields, personalisation opt-out
--   im_newsletter_subscribers + unsubscribe token and consent record
--   im_privacy_requests     RA 10173 data-subject requests
--   im_contact_messages     the public contact form's inbox
--   storage `product-media` public bucket for product and shop photos
--                             (ADR-4: out of base64-in-Postgres)
--
-- Every new table: RLS on, read only what a user may see, no client writes
-- (the application writes with the service role after its own checks).
--
-- Rollback: supabase/rollback/0019_down.sql

begin;

-- ---------------------------------------------------------------------------
-- Addresses
-- ---------------------------------------------------------------------------
create table if not exists public.im_addresses (
  id          bigint generated by default as identity primary key,
  profile_id  bigint not null references public.im_profiles(id) on delete cascade,
  label       text check (label is null or length(label) <= 40),
  recipient   text not null check (length(trim(recipient)) between 2 and 120),
  phone       text not null check (phone ~ '^(\+?63|0)[0-9]{9,10}$'),
  line1       text not null check (length(trim(line1)) between 3 and 300),
  barangay    text check (barangay is null or length(barangay) <= 120),
  city        text not null check (length(trim(city)) between 2 and 80),
  province    text check (province is null or length(province) <= 80),
  postal_code text check (postal_code is null or postal_code ~ '^[0-9]{4}$'),
  is_default  boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists idx_im_addresses_profile on public.im_addresses(profile_id);
create unique index if not exists idx_im_addresses_one_default
  on public.im_addresses(profile_id) where is_default;
alter table public.im_addresses enable row level security;
drop policy if exists im_addresses_own_read on public.im_addresses;
create policy im_addresses_own_read on public.im_addresses for select
  using (profile_id = public.im_current_profile_id());
revoke insert, update, delete, truncate on public.im_addresses from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Reviews: moderation, seller reply, the order line behind it
-- ---------------------------------------------------------------------------
alter table public.im_product_reviews
  add column if not exists order_item_id   bigint references public.im_order_items(id) on delete set null,
  add column if not exists status          text not null default 'visible' check (status in ('visible', 'hidden')),
  add column if not exists hidden_reason   text,
  add column if not exists hidden_by       bigint references public.im_profiles(id) on delete set null,
  add column if not exists hidden_at       timestamptz,
  add column if not exists seller_reply    text check (seller_reply is null or length(seller_reply) <= 1000),
  add column if not exists seller_reply_at timestamptz,
  add column if not exists updated_at      timestamptz;

-- Hidden reviews leave the public catalogue and the rating.
drop policy if exists im_reviews_public_read on public.im_product_reviews;
create policy im_reviews_public_read on public.im_product_reviews for select
  using (status = 'visible'
         or buyer_id = public.im_current_profile_id()
         or public.im_current_profile_role() = 'admin');

create or replace function public.im_refresh_product_rating(p_product_id bigint)
returns void language sql security definer set search_path = '' as $fn$
  update public.im_products p
     set rating_avg = coalesce((select round(avg(r.rating_score)::numeric, 2) from public.im_product_reviews r
                                 where r.product_id = p_product_id and r.status = 'visible'), 0),
         rating_count = (select count(*) from public.im_product_reviews r
                          where r.product_id = p_product_id and r.status = 'visible')
   where p.id = p_product_id;
$fn$;

-- ---------------------------------------------------------------------------
-- Notifications: more types, per-type preferences
-- ---------------------------------------------------------------------------
alter table public.im_notifications drop constraint if exists im_notifications_type_check;
alter table public.im_notifications add constraint im_notifications_type_check
  check (type in ('low_stock', 'new_order', 'shipping_update', 'new_review', 'flash_sale',
                  'order_status', 'message', 'chat_escalation', 'system',
                  'pwd_verification', 'moderation', 'review_reply', 'payout', 'account'));
create index if not exists idx_im_notifications_user_created
  on public.im_notifications(user_id, created_at desc);

create table if not exists public.im_notification_prefs (
  profile_id bigint not null references public.im_profiles(id) on delete cascade,
  type       text not null,
  in_app     boolean not null default true,
  email      boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (profile_id, type)
);
alter table public.im_notification_prefs enable row level security;
drop policy if exists im_notification_prefs_own_read on public.im_notification_prefs;
create policy im_notification_prefs_own_read on public.im_notification_prefs for select
  using (profile_id = public.im_current_profile_id());
revoke insert, update, delete, truncate on public.im_notification_prefs from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Product views (recommendations). Behavioural data: signed-in buyers only,
-- 90-day retention (purged opportunistically by the app), opt-out on the
-- profile, disclosed in the Privacy Policy. Service role only.
-- ---------------------------------------------------------------------------
create table if not exists public.im_product_views (
  id         bigint generated by default as identity primary key,
  profile_id bigint not null references public.im_profiles(id) on delete cascade,
  product_id bigint not null references public.im_products(id) on delete cascade,
  viewed_at  timestamptz not null default now()
);
create index if not exists idx_im_product_views_profile on public.im_product_views(profile_id, viewed_at desc);
create index if not exists idx_im_product_views_age on public.im_product_views(viewed_at);
alter table public.im_product_views enable row level security;
revoke insert, update, delete, truncate on public.im_product_views from anon, authenticated;

alter table public.im_profiles
  add column if not exists personalization_opt_out boolean not null default false,
  add column if not exists shop_name       text check (shop_name is null or length(shop_name) between 2 and 80),
  add column if not exists shop_logo_url   text,
  add column if not exists shop_banner_url text,
  add column if not exists pickup_city     text check (pickup_city is null or length(pickup_city) <= 80);

-- Public seller projection gains the shop fields (still no contact details or
-- disability data). Columns are appended so the view's shape stays compatible.
create or replace view public.im_public_sellers
with (security_invoker = false) as
  select p.id, p.name, p.seller_story, p.is_featured_seller,
         p.shop_name, p.shop_logo_url, p.shop_banner_url, p.pickup_city, p.created_at
    from public.im_profiles p
   where p.role = 'seller' and p.account_status = 'active';
grant select on public.im_public_sellers to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Homepage banners
-- ---------------------------------------------------------------------------
create table if not exists public.im_banners (
  id         bigint generated by default as identity primary key,
  title      text not null check (length(trim(title)) between 2 and 120),
  alt_text   text not null check (length(trim(alt_text)) between 2 and 200),
  image_url  text not null,
  -- Internal links only: a banner is never a phishing redirect.
  link_url   text check (link_url is null or link_url ~ '^/[A-Za-z0-9/_?=&%.-]*$'),
  starts_at  timestamptz not null default now(),
  ends_at    timestamptz,
  position   integer not null default 0,
  is_active  boolean not null default true,
  created_by bigint references public.im_profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  check (ends_at is null or ends_at > starts_at)
);
alter table public.im_banners enable row level security;
revoke insert, update, delete, truncate on public.im_banners from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Newsletter: unsubscribe token and consent
-- ---------------------------------------------------------------------------
alter table public.im_newsletter_subscribers
  add column if not exists unsubscribe_token text not null default replace(gen_random_uuid()::text, '-', ''),
  add column if not exists consent_text text;
create unique index if not exists idx_im_newsletter_token on public.im_newsletter_subscribers(unsubscribe_token);

-- ---------------------------------------------------------------------------
-- Data-subject requests (RA 10173): access, correction, deletion, objection
-- ---------------------------------------------------------------------------
create table if not exists public.im_privacy_requests (
  id         bigint generated by default as identity primary key,
  profile_id bigint references public.im_profiles(id) on delete set null,
  kind       text not null check (kind in ('access', 'correction', 'deletion', 'objection')),
  details    text check (details is null or length(details) <= 2000),
  status     text not null default 'open' check (status in ('open', 'in_progress', 'done', 'rejected')),
  response   text,
  handled_by bigint references public.im_profiles(id) on delete set null,
  handled_at timestamptz,
  created_at timestamptz not null default now()
);
alter table public.im_privacy_requests enable row level security;
drop policy if exists im_privacy_requests_read on public.im_privacy_requests;
create policy im_privacy_requests_read on public.im_privacy_requests for select
  using (profile_id = public.im_current_profile_id() or public.im_current_profile_role() = 'admin');
revoke insert, update, delete, truncate on public.im_privacy_requests from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Contact form inbox (guests included). Admin-only.
-- ---------------------------------------------------------------------------
create table if not exists public.im_contact_messages (
  id         bigint generated by default as identity primary key,
  profile_id bigint references public.im_profiles(id) on delete set null,
  name       text not null check (length(trim(name)) between 2 and 120),
  email      text not null check (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  topic      text not null check (topic in ('question', 'order', 'selling', 'accessibility', 'privacy', 'other')),
  message    text not null check (length(trim(message)) between 5 and 4000),
  consent    boolean not null default false,
  status     text not null default 'new' check (status in ('new', 'answered', 'closed')),
  created_at timestamptz not null default now()
);
create index if not exists idx_im_contact_status on public.im_contact_messages(status, created_at desc);
alter table public.im_contact_messages enable row level security;
drop policy if exists im_contact_admin_read on public.im_contact_messages;
create policy im_contact_admin_read on public.im_contact_messages for select
  using (public.im_current_profile_role() = 'admin');
revoke insert, update, delete, truncate on public.im_contact_messages from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Public bucket for product and shop photos. Reads go through the public URL;
-- writes only through the application (service role).
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-media', 'product-media', true, 1572864, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
  set public = true,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists im_product_media_no_client_writes on storage.objects;
create policy im_product_media_no_client_writes on storage.objects
  as restrictive
  for all
  to anon, authenticated
  using (bucket_id <> 'product-media')
  with check (bucket_id <> 'product-media');

commit;
