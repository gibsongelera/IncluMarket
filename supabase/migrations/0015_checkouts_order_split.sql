-- InclusiveMarket — one order per seller, grouped by a checkout.
--
-- Before: one im_orders row held items from several sellers. Any seller with a
-- line in it could change the whole order's status, and saw the other sellers'
-- lines and the full total (B-09). placeOrder also wrote the order, its lines
-- and the stock decrements as separate requests, unwinding failures by hand
-- (B-07).
--
-- After:
--   * im_checkouts — what the buyer paid for in one go: payment provider,
--     status and reference, and the grand total.
--   * im_orders gains seller_id, checkout_id, subtotal and shipping_fee: each
--     order is ONE seller's parcel, with its own status machine (0014).
--   * im_order_items gains the pricing breakdown (ADR-6): base price, flash
--     sale, PWD discount and its legal basis, so reports can substantiate
--     every discount. Foreign keys to the discount-rule and verification
--     tables are added by the migrations that create those tables.
--   * im_place_checkout(): the whole checkout — checkout row, per-seller
--     orders, lines, history and every stock decrement — in ONE transaction.
--     A line that no longer fits raises and rolls everything back; there is
--     nothing to unwind.
--
-- Legacy orders: each gets a checkout of its own. An order that held several
-- sellers' lines is split into one order per seller (production had none when
-- this was written; the split is here for any environment that does).
--
-- Rollback: supabase/rollback/0015_down.sql

begin;

-- ---------------------------------------------------------------------------
-- Tables and columns
-- ---------------------------------------------------------------------------
create table if not exists public.im_checkouts (
  id                bigint generated by default as identity primary key,
  buyer_id          bigint not null references public.im_profiles(id) on delete cascade,
  payment_provider  text references public.im_payment_providers(id) on delete set null,
  payment_status    text not null default 'unpaid'
                      check (payment_status in ('unpaid','pending','paid','failed','refunded')),
  payment_reference text,
  grand_total       numeric(12,2) not null check (grand_total >= 0),
  created_at        timestamptz not null default now()
);
create index if not exists idx_im_checkouts_buyer on public.im_checkouts(buyer_id);
create unique index if not exists idx_im_checkouts_payment_ref
  on public.im_checkouts(payment_reference) where payment_reference is not null;

alter table public.im_checkouts enable row level security;
drop policy if exists im_checkouts_read on public.im_checkouts;
create policy im_checkouts_read on public.im_checkouts for select
  using (buyer_id = public.im_current_profile_id() or public.im_current_profile_role() = 'admin');
revoke insert, update, delete, truncate on public.im_checkouts from anon, authenticated;

alter table public.im_orders
  add column if not exists seller_id    bigint references public.im_profiles(id) on delete set null,
  add column if not exists checkout_id  bigint references public.im_checkouts(id) on delete set null,
  add column if not exists subtotal     numeric(12,2),
  add column if not exists shipping_fee numeric(12,2) not null default 0;
create index if not exists idx_im_orders_seller   on public.im_orders(seller_id);
create index if not exists idx_im_orders_checkout on public.im_orders(checkout_id);

-- Several orders now share one PayMongo session, so the reference cannot be
-- unique per order any more; uniqueness moves to im_checkouts.
drop index if exists public.idx_im_orders_payment_ref;
create index if not exists idx_im_orders_payment_ref on public.im_orders(payment_reference);

alter table public.im_order_items
  add column if not exists base_unit_price     numeric(12,2),
  add column if not exists flash_sale_id       bigint references public.im_flash_sales(id) on delete set null,
  add column if not exists sale_discount_pct   numeric(5,2),
  add column if not exists pwd_rule_id         bigint,
  add column if not exists pwd_rate            numeric(5,2),
  add column if not exists pwd_discount_amount numeric(12,2) not null default 0,
  add column if not exists pwd_eligible_amount numeric(12,2) not null default 0,
  add column if not exists vat_exempt_amount   numeric(12,2) not null default 0,
  add column if not exists legal_basis         text,
  add column if not exists verification_id     bigint;

-- ---------------------------------------------------------------------------
-- Visibility: an order's seller is now a column.
-- ---------------------------------------------------------------------------
create or replace function public.im_can_see_order(p_order_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $fn$
  select
    public.im_current_profile_role() = 'admin'
    or exists (
      select 1 from public.im_orders o
       where o.id = p_order_id
         and (o.buyer_id = public.im_current_profile_id() or o.seller_id = public.im_current_profile_id())
    )
    or exists (
      select 1
        from public.im_order_items oi
        join public.im_products p on p.id = oi.product_id
       where oi.order_id = p_order_id and p.seller_id = public.im_current_profile_id()
    );
$fn$;

-- ---------------------------------------------------------------------------
-- Backfill
-- ---------------------------------------------------------------------------
do $backfill$
declare
  o        record;
  s        record;
  first    boolean;
  new_id   bigint;
  v_status text;
  v_items  numeric(12,2);
  v_ship   numeric(12,2);
begin
  -- 1. Split orders holding more than one seller's lines.
  for o in
    select ord.*
      from public.im_orders ord
     where (select count(distinct p.seller_id)
              from public.im_order_items oi join public.im_products p on p.id = oi.product_id
             where oi.order_id = ord.id) > 1
  loop
    -- Shipping is what the total held beyond ALL its lines, measured before
    -- any line moves; it stays with the first seller's part.
    select coalesce(sum(unit_price * quantity), 0) into v_items
      from public.im_order_items where order_id = o.id;
    v_ship := greatest(o.total_amount - v_items, 0);
    first := true;
    for s in
      select p.seller_id
        from public.im_order_items oi join public.im_products p on p.id = oi.product_id
       where oi.order_id = o.id
       group by p.seller_id
       order by p.seller_id
    loop
      if first then
        update public.im_orders set seller_id = s.seller_id where id = o.id;
        first := false;
      else
        -- New orders must start pending (0014); copy the status afterwards.
        insert into public.im_orders (buyer_id, total_amount, order_status, payment_status, payment_provider,
                                      payment_reference, shipping_name, shipping_address, shipping_city,
                                      shipping_phone, created_at, seller_id, shipping_fee)
        values (o.buyer_id, 0, 'pending', o.payment_status, o.payment_provider, o.payment_reference,
                o.shipping_name, o.shipping_address, o.shipping_city, o.shipping_phone, o.created_at,
                s.seller_id, 0)
        returning id into new_id;
        v_status := o.order_status;
        if v_status <> 'pending' then
          perform set_config('im.transition', 'on', true);
          update public.im_orders set order_status = v_status where id = new_id;
          perform set_config('im.transition', 'off', true);
        end if;
        update public.im_order_items oi set order_id = new_id
          from public.im_products p
         where p.id = oi.product_id and oi.order_id = o.id and p.seller_id = s.seller_id;
        insert into public.im_order_status_history (order_id, status, note, created_by, created_at, actor_role)
        select new_id, h.status, coalesce(h.note, '') || ' (split from order #' || o.id || ')', h.created_by, h.created_at, h.actor_role
          from public.im_order_status_history h where h.order_id = o.id;
        update public.im_orders
           set subtotal = (select coalesce(sum(unit_price * quantity), 0) from public.im_order_items where order_id = new_id)
         where id = new_id;
        update public.im_orders set total_amount = subtotal where id = new_id;
      end if;
    end loop;
    update public.im_orders
       set shipping_fee = v_ship,
           subtotal = (select coalesce(sum(unit_price * quantity), 0) from public.im_order_items where order_id = o.id)
     where id = o.id;
    update public.im_orders set total_amount = subtotal + shipping_fee where id = o.id;
  end loop;

  -- 2. seller_id for every single-seller order.
  update public.im_orders ord
     set seller_id = sub.seller_id
    from (
      select oi.order_id, min(p.seller_id) as seller_id
        from public.im_order_items oi join public.im_products p on p.id = oi.product_id
       group by oi.order_id
    ) sub
   where sub.order_id = ord.id and ord.seller_id is null;

  -- 3. subtotal from the lines; shipping is whatever the total held beyond it
  --    (a split order's extra parts carry no shipping: the buyer paid once).
  update public.im_orders ord
     set subtotal = coalesce((select sum(oi.unit_price * oi.quantity) from public.im_order_items oi where oi.order_id = ord.id), 0)
   where ord.subtotal is null;
  update public.im_orders
     set shipping_fee = greatest(total_amount - subtotal, 0)
   where shipping_fee = 0 and total_amount > subtotal;
  update public.im_orders
     set total_amount = subtotal + shipping_fee
   where total_amount = 0 and subtotal > 0;

  -- 4. A checkout per legacy order (split parts share their original's).
  for o in select * from public.im_orders where checkout_id is null order by id loop
    -- The loop reads a snapshot: a split part may have been given its
    -- original's checkout earlier in this loop.
    if exists (select 1 from public.im_orders where id = o.id and checkout_id is not null) then
      continue;
    end if;
    insert into public.im_checkouts (buyer_id, payment_provider, payment_status, payment_reference, grand_total, created_at)
    values (o.buyer_id, o.payment_provider, o.payment_status, null, o.total_amount, o.created_at)
    returning id into new_id;
    update public.im_orders
       set checkout_id = new_id
     where checkout_id is null
       and buyer_id = o.buyer_id
       and created_at = o.created_at
       and coalesce(payment_reference, '') = coalesce(o.payment_reference, '');
    update public.im_checkouts c
       set grand_total = (select sum(total_amount) from public.im_orders where checkout_id = new_id),
           payment_reference = o.payment_reference
     where c.id = new_id;
  end loop;
end
$backfill$;

-- ---------------------------------------------------------------------------
-- Place a checkout atomically.
--
-- p: { buyer_id, payment_provider: 'cod'|'paymongo',
--      shipping: { name, address, city, phone },
--      cart_item_ids: [..],                        -- COD: removed from the cart
--      groups: [ { seller_id, shipping_fee,
--                  lines: [ { product_id, variant_id, quantity, unit_price,
--                             base_unit_price, flash_sale_id, sale_discount_pct,
--                             pwd_rule_id, pwd_rate, pwd_discount_amount,
--                             pwd_eligible_amount, vat_exempt_amount,
--                             legal_basis, verification_id } ] } ] }
--
-- Prices are computed by the application's pricing engine and passed in; this
-- function is callable by the service role only. It re-checks what must hold
-- at the instant of the sale — product approved, variant belongs to it,
-- seller matches the group, stock available — and decrements stock in the
-- same statement as that check.
--
-- Raises 'out_of_stock:<product_id>' or 'unavailable:<product_id>'; the
-- whole checkout then rolls back.
-- ---------------------------------------------------------------------------
create or replace function public.im_place_checkout(p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_buyer     bigint := (p->>'buyer_id')::bigint;
  v_provider  text   := p->>'payment_provider';
  v_pay       text;
  v_checkout  bigint;
  v_order     bigint;
  v_grand     numeric(12,2) := 0;
  v_sub       numeric(12,2);
  v_fee       numeric(12,2);
  v_orders    bigint[] := '{}';
  g           jsonb;
  l           jsonb;
  v_updated   integer;
begin
  if v_provider not in ('cod', 'paymongo') then
    raise exception 'bad_provider' using errcode = 'P0001';
  end if;
  if not exists (select 1 from public.im_profiles where id = v_buyer and role = 'buyer' and account_status = 'active') then
    raise exception 'bad_buyer' using errcode = 'P0001';
  end if;
  if jsonb_array_length(coalesce(p->'groups', '[]'::jsonb)) = 0 then
    raise exception 'empty' using errcode = 'P0001';
  end if;
  v_pay := case when v_provider = 'cod' then 'unpaid' else 'pending' end;

  insert into public.im_checkouts (buyer_id, payment_provider, payment_status, grand_total)
  values (v_buyer, v_provider, v_pay, 0)
  returning id into v_checkout;

  for g in select * from jsonb_array_elements(p->'groups') loop
    v_fee := coalesce((g->>'shipping_fee')::numeric, 0);
    select coalesce(sum((x->>'unit_price')::numeric * (x->>'quantity')::integer), 0)
      into v_sub
      from jsonb_array_elements(g->'lines') x;

    insert into public.im_orders (buyer_id, seller_id, checkout_id, total_amount, subtotal, shipping_fee,
                                  order_status, payment_status, payment_provider,
                                  shipping_name, shipping_address, shipping_city, shipping_phone)
    values (v_buyer, (g->>'seller_id')::bigint, v_checkout, v_sub + v_fee, v_sub, v_fee,
            'pending', v_pay, v_provider,
            p->'shipping'->>'name', p->'shipping'->>'address', p->'shipping'->>'city', p->'shipping'->>'phone')
    returning id into v_order;
    v_orders := v_orders || v_order;
    v_grand := v_grand + v_sub + v_fee;

    insert into public.im_order_status_history (order_id, status, created_by, actor_role)
    values (v_order, 'pending', v_buyer, 'buyer');

    for l in select * from jsonb_array_elements(g->'lines') loop
      update public.im_product_variants v
         set stock_qty = v.stock_qty - (l->>'quantity')::integer
       where v.id = (l->>'variant_id')::bigint
         and v.product_id = (l->>'product_id')::bigint
         and v.stock_qty >= (l->>'quantity')::integer
         and exists (
           select 1 from public.im_products pr
            where pr.id = v.product_id
              and pr.status = 'approved'
              and pr.seller_id = (g->>'seller_id')::bigint
         );
      get diagnostics v_updated = row_count;
      if v_updated = 0 then
        if exists (select 1 from public.im_products pr
                    where pr.id = (l->>'product_id')::bigint and pr.status = 'approved') then
          raise exception 'out_of_stock:%', l->>'product_id' using errcode = 'P0001';
        end if;
        raise exception 'unavailable:%', l->>'product_id' using errcode = 'P0001';
      end if;

      insert into public.im_order_items (
        order_id, product_id, variant_id, quantity, unit_price,
        base_unit_price, flash_sale_id, sale_discount_pct,
        pwd_rule_id, pwd_rate, pwd_discount_amount, pwd_eligible_amount, vat_exempt_amount,
        legal_basis, verification_id)
      values (
        v_order, (l->>'product_id')::bigint, (l->>'variant_id')::bigint, (l->>'quantity')::integer,
        (l->>'unit_price')::numeric,
        nullif(l->>'base_unit_price', '')::numeric, nullif(l->>'flash_sale_id', '')::bigint,
        nullif(l->>'sale_discount_pct', '')::numeric,
        nullif(l->>'pwd_rule_id', '')::bigint, nullif(l->>'pwd_rate', '')::numeric,
        coalesce(nullif(l->>'pwd_discount_amount', '')::numeric, 0),
        coalesce(nullif(l->>'pwd_eligible_amount', '')::numeric, 0),
        coalesce(nullif(l->>'vat_exempt_amount', '')::numeric, 0),
        nullif(l->>'legal_basis', ''), nullif(l->>'verification_id', '')::bigint);
    end loop;
  end loop;

  update public.im_checkouts set grand_total = v_grand where id = v_checkout;

  -- Cash on delivery is final now: take the ordered lines out of the cart in
  -- the same transaction. Online payments keep them until the webhook.
  if v_provider = 'cod' and jsonb_typeof(p->'cart_item_ids') = 'array' then
    delete from public.im_cart_items
     where user_id = v_buyer
       and id in (select (x #>> '{}')::bigint from jsonb_array_elements(p->'cart_item_ids') x);
  end if;

  return jsonb_build_object('checkout_id', v_checkout, 'order_ids', to_jsonb(v_orders), 'grand_total', v_grand);
end;
$fn$;
revoke all on function public.im_place_checkout(jsonb) from public, anon, authenticated;

commit;
