-- 0027 — Sold-out audit and kept item history.
--
-- 1. im_stock_events: the moment a listing sells out (its stock_total, kept
--    by the 0016 triggers, falls from above 0 to 0) and the moment it comes
--    back in stock after that. Admin → Sold-out audit reads "sold out on"
--    from here. Listings already sold out when this runs get one event dated
--    from their last sale, marked approximate.
--
--    A seller saving the product form can pass through 0 for a moment (an
--    option deleted before its replacement is added). A sell-out undone
--    within two minutes is that, not a sell-out, and is dropped instead of
--    being answered with "back in stock".
--
-- 2. im_item_history: what used to vanish. A photo taken off a listing, or a
--    listing deleted outright (the app has not hard-deleted listings since
--    0016, but the Supabase table editor can), is copied here first: title,
--    seller, price, stock, units sold, options and the photo URLs. Storage
--    files are never deleted with the row, so the old photo still opens.
--    Inline (data:) photos from before 0023 are counted, not copied: no new
--    base64 in Postgres.
--
--    Who removed it: the app deletes photos through im_remove_product_photos,
--    which records the signed-in seller or admin. A deletion anywhere else is
--    kept with no actor, and the page says it happened outside the app.
--
-- Surface B: both tables are admin-read only, with no client write rule, and
-- the function is service-role only.
--
-- Rollback: supabase/rollback/0027_down.sql

begin;

-- ---------------------------------------------------------------------------
-- Stock events
-- ---------------------------------------------------------------------------
create table if not exists public.im_stock_events (
  id           bigint generated by default as identity primary key,
  -- No foreign keys: the record outlives the listing and the account.
  product_id   bigint not null,
  seller_id    bigint,
  title        text not null,
  kind         text not null check (kind in ('sold_out', 'restocked')),
  -- Null when unknown (the backfill).
  stock_before integer,
  stock_after  integer not null default 0,
  approximate  boolean not null default false,
  occurred_at  timestamptz not null default now()
);
create index if not exists idx_im_stock_events_time    on public.im_stock_events (occurred_at desc);
create index if not exists idx_im_stock_events_product on public.im_stock_events (product_id, occurred_at desc);

alter table public.im_stock_events enable row level security;
drop policy if exists im_stock_events_admin_read on public.im_stock_events;
create policy im_stock_events_admin_read on public.im_stock_events for select
  using (public.im_current_profile_role() = 'admin');
revoke insert, update, delete, truncate on public.im_stock_events from anon, authenticated;

create or replace function public.im_products_stock_events()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_last record;
begin
  select e.id, e.kind, e.occurred_at, e.approximate
    into v_last
    from public.im_stock_events e
   where e.product_id = new.id
   order by e.occurred_at desc, e.id desc
   limit 1;

  if old.stock_total > 0 and new.stock_total <= 0 then
    insert into public.im_stock_events (product_id, seller_id, title, kind, stock_before, stock_after)
    values (new.id, new.seller_id, new.title, 'sold_out', old.stock_total, new.stock_total);
  elsif old.stock_total <= 0 and new.stock_total > 0 and v_last.kind = 'sold_out' then
    -- Back above 0 within two minutes of reaching it: a form save passing
    -- through 0, not a sell-out. (A backfilled event is never "recent".)
    if not v_last.approximate and v_last.occurred_at > now() - interval '2 minutes' then
      delete from public.im_stock_events where id = v_last.id;
    else
      insert into public.im_stock_events (product_id, seller_id, title, kind, stock_before, stock_after)
      values (new.id, new.seller_id, new.title, 'restocked', old.stock_total, new.stock_total);
    end if;
  end if;
  return null;
end;
$fn$;

drop trigger if exists im_products_stock_events on public.im_products;
create trigger im_products_stock_events
  after update of stock_total on public.im_products
  for each row
  when (old.stock_total is distinct from new.stock_total)
  execute function public.im_products_stock_events();

-- Listings sold out before today: one event each, dated from the last order
-- that still counts as a sale (else the listing's last update).
insert into public.im_stock_events (product_id, seller_id, title, kind, stock_before, stock_after, approximate, occurred_at)
select p.id, p.seller_id, p.title, 'sold_out', null, p.stock_total, true,
       coalesce(
         (select max(o.created_at)
            from public.im_order_items oi
            join public.im_orders o on o.id = oi.order_id
           where oi.product_id = p.id and o.order_status <> 'cancelled'),
         p.updated_at,
         p.created_at)
  from public.im_products p
 where p.stock_total <= 0
   and p.sold_count > 0
   and not exists (select 1 from public.im_stock_events e where e.product_id = p.id);

-- ---------------------------------------------------------------------------
-- Item history
-- ---------------------------------------------------------------------------
create table if not exists public.im_item_history (
  id            bigint generated by default as identity primary key,
  -- No foreign keys: the record outlives the listing and the account.
  product_id    bigint not null,
  seller_id     bigint,
  seller_name   text,
  kind          text not null check (kind in ('photo_removed', 'item_deleted')),
  title         text not null,
  photos        text[] not null default '{}',
  inline_photos integer not null default 0,
  base_price    numeric(12,2),
  category      text,
  stock_total   integer,
  sold_count    integer,
  details       jsonb not null default '{}'::jsonb,
  actor_id      bigint,
  actor_role    text,
  created_at    timestamptz not null default now()
);
create index if not exists idx_im_item_history_time    on public.im_item_history (created_at desc);
create index if not exists idx_im_item_history_product on public.im_item_history (product_id);

alter table public.im_item_history enable row level security;
drop policy if exists im_item_history_admin_read on public.im_item_history;
create policy im_item_history_admin_read on public.im_item_history for select
  using (public.im_current_profile_role() = 'admin');
revoke insert, update, delete, truncate on public.im_item_history from anon, authenticated;

-- One photo taken off a listing that still exists.
create or replace function public.im_product_images_history()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  p record;
  v_inline boolean := old.url like 'data:%';
begin
  select pr.id, pr.seller_id, pr.title, pr.base_price, pr.category, pr.stock_total, pr.sold_count
    into p
    from public.im_products pr
   where pr.id = old.product_id;
  -- The listing itself is being deleted: im_products_history() has already
  -- kept it with every photo.
  if not found then
    return null;
  end if;

  insert into public.im_item_history
    (product_id, seller_id, seller_name, kind, title, photos, inline_photos,
     base_price, category, stock_total, sold_count, details, actor_id, actor_role)
  values
    (p.id, p.seller_id, (select s.name from public.im_profiles s where s.id = p.seller_id),
     'photo_removed', p.title,
     case when v_inline then '{}'::text[] else array[old.url] end,
     case when v_inline then 1 else 0 end,
     p.base_price, p.category, p.stock_total, p.sold_count,
     jsonb_build_object('position', old.position),
     nullif(current_setting('im.history_actor_id', true), '')::bigint,
     nullif(current_setting('im.history_actor_role', true), ''));
  return null;
end;
$fn$;

drop trigger if exists im_product_images_history on public.im_product_images;
create trigger im_product_images_history
  after delete on public.im_product_images
  for each row execute function public.im_product_images_history();

-- A whole listing deleted: kept with its photos and options.
create or replace function public.im_products_history()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_photos text[];
  v_inline integer;
  v_options jsonb;
begin
  select coalesce(array_agg(i.url order by i.position, i.id) filter (where i.url not like 'data:%'), '{}'),
         count(*) filter (where i.url like 'data:%')
    into v_photos, v_inline
    from public.im_product_images i
   where i.product_id = old.id;

  select jsonb_agg(jsonb_build_object('option', v.color_name, 'size', v.size, 'stock', v.stock_qty, 'sku', v.sku_code)
                   order by v.id)
    into v_options
    from public.im_product_variants v
   where v.product_id = old.id;

  -- createProduct deletes a listing whose options failed to save (a SKU
  -- already taken) moments after inserting it: nothing was ever listed.
  if v_options is null and cardinality(v_photos) = 0 and v_inline = 0
     and old.created_at > now() - interval '1 hour' then
    return old;
  end if;

  insert into public.im_item_history
    (product_id, seller_id, seller_name, kind, title, photos, inline_photos,
     base_price, category, stock_total, sold_count, details, actor_id, actor_role)
  values
    (old.id, old.seller_id, (select s.name from public.im_profiles s where s.id = old.seller_id),
     'item_deleted', old.title, v_photos, v_inline,
     old.base_price, old.category, old.stock_total, old.sold_count,
     jsonb_build_object(
       'status', old.status,
       'description', left(coalesce(old.description, ''), 2000),
       'listed_at', old.created_at,
       'options', coalesce(v_options, '[]'::jsonb)),
     nullif(current_setting('im.history_actor_id', true), '')::bigint,
     nullif(current_setting('im.history_actor_role', true), ''));
  return old;
end;
$fn$;

drop trigger if exists im_products_history on public.im_products;
create trigger im_products_history
  before delete on public.im_products
  for each row execute function public.im_products_history();

-- The app's way to take photos off a listing, so the history names who did.
-- Rows are matched by id AND listing, so an id from another listing does
-- nothing.
create or replace function public.im_remove_product_photos(
  p_product_id bigint,
  p_image_ids  bigint[],
  p_actor_id   bigint,
  p_actor_role text
)
returns integer
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  n integer;
begin
  perform set_config('im.history_actor_id', coalesce(p_actor_id::text, ''), true);
  perform set_config('im.history_actor_role', coalesce(p_actor_role, ''), true);
  delete from public.im_product_images
   where product_id = p_product_id
     and id = any(coalesce(p_image_ids, '{}'::bigint[]));
  get diagnostics n = row_count;
  perform set_config('im.history_actor_id', '', true);
  perform set_config('im.history_actor_role', '', true);
  return n;
end;
$fn$;

revoke all on function public.im_remove_product_photos(bigint, bigint[], bigint, text) from public, anon, authenticated;

comment on table public.im_stock_events is
  'When a listing sold out and when it came back in stock (0027). Admin-read only.';
comment on table public.im_item_history is
  'Photos taken off listings and listings deleted, kept with their photo URLs and details (0027). Admin-read only.';

commit;
