-- InclusiveMarket — PWD ID verification.
--
-- Client requirement (§6): a PWD ID is scanned and submitted, reviewed by AVRC
-- staff, and is the gate for (a) a seller's listings going live and (b) a
-- buyer's PWD discount. It must resist scams. A PWD ID and disability
-- information are SENSITIVE personal information under RA 10173.
--
-- Design (ADR-7):
--   * Images live in a PRIVATE Storage bucket `pwd-ids`, never as base64 in
--     a table and never behind a public URL. Only the service role reads it;
--     admins view images through ~60-second signed URLs the app creates and
--     logs. A RESTRICTIVE storage policy denies anon/authenticated on this
--     bucket whatever other (permissive) policies the shared project holds.
--   * The ID number is stored as an HMAC (keyed hash: the national number
--     format leaves few enough possibilities that a plain hash could be
--     brute-forced) for the one-account-per-number rule, plus its last four
--     digits for display. The full number is kept AES-256-GCM-encrypted only
--     while the submission waits for review, so the admin can paste it into
--     the DOH registry, and is wiped at the decision.
--   * A partial unique index makes "one active ID number, one account" a
--     database guarantee, not an application check.
--   * im_verified_pwd is the single source of "verified": the latest approved,
--     unrevoked, unexpired verification. Expiry needs no scheduled job.
--   * Sellers sell only when verified. Existing sellers get a grace period
--     (setting seller_verification_grace_days, default 30 — client Q4).
--
-- Rollback: supabase/rollback/0017_down.sql

begin;

-- ---------------------------------------------------------------------------
-- Settings the client has not confirmed (editable later, no deploy)
-- ---------------------------------------------------------------------------
insert into public.im_settings (key, value, note) values
  ('pwd_id_retention_days',          '30', 'Days after a decision before ID images are deleted (Q3).'),
  ('seller_verification_grace_days', '30', 'Days existing sellers keep selling before they must be verified (Q4).'),
  ('pwd_review_target_days',         '2',  'Business days we tell users a review takes (Q2).'),
  ('pwd_renewal_reminder_days',      '30', 'Days before an ID expires that we remind the user.')
on conflict (key) do nothing;

-- ---------------------------------------------------------------------------
-- Verifications
-- ---------------------------------------------------------------------------
create table if not exists public.im_pwd_verifications (
  id                  bigint generated by default as identity primary key,
  profile_id          bigint not null references public.im_profiles(id) on delete cascade,
  method              text not null default 'id_scan' check (method in ('id_scan', 'avrc_in_person')),
  id_number_hash      text,
  id_number_last4     text check (id_number_last4 is null or id_number_last4 ~ '^[0-9]{4}$'),
  id_number_encrypted text,
  issuing_lgu         text,
  expires_on          date,
  front_path          text,
  back_path           text,
  selfie_path         text,
  status              text not null default 'submitted'
                        check (status in ('submitted', 'approved', 'rejected', 'expired', 'revoked')),
  registry_result     text check (registry_result in ('found', 'not_found', 'not_checked')),
  registry_check_note text,
  reviewer_id         bigint references public.im_profiles(id) on delete set null,
  reviewed_at         timestamptz,
  reason_code         text,
  reason              text,
  consent_log_id      bigint references public.im_consent_logs(id) on delete set null,
  images_deleted_at   timestamptz,
  reminder_sent_at    timestamptz,
  revoked_at          timestamptz,
  revoked_by          bigint references public.im_profiles(id) on delete set null,
  revoke_reason       text,
  submitted_at        timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  -- An ID scan always has its number and images; an in-person check has none.
  constraint im_pwd_verifications_scan_complete check (
    method = 'avrc_in_person'
    or (id_number_hash is not null and id_number_last4 is not null and expires_on is not null)
  )
);

-- One active ID number, one account: a second submission of a number that is
-- under review or approved anywhere fails at the database.
create unique index if not exists idx_im_pwd_number_active
  on public.im_pwd_verifications(id_number_hash)
  where status in ('submitted', 'approved') and id_number_hash is not null;
-- One open submission per person at a time.
create unique index if not exists idx_im_pwd_one_open
  on public.im_pwd_verifications(profile_id)
  where status = 'submitted';
create index if not exists idx_im_pwd_profile on public.im_pwd_verifications(profile_id, status);
create index if not exists idx_im_pwd_status  on public.im_pwd_verifications(status, submitted_at);

-- Duplicate-number attempts, for admins to look at (anti-scam).
create table if not exists public.im_pwd_verification_flags (
  id                       bigint generated by default as identity primary key,
  profile_id               bigint not null references public.im_profiles(id) on delete cascade,
  id_number_hash           text not null,
  existing_verification_id bigint references public.im_pwd_verifications(id) on delete set null,
  kind                     text not null default 'duplicate_id' check (kind in ('duplicate_id', 'expired_id', 'rate_limited')),
  note                     text,
  created_at               timestamptz not null default now(),
  resolved_at              timestamptz,
  resolved_by              bigint references public.im_profiles(id) on delete set null
);
create index if not exists idx_im_pwd_flags_open on public.im_pwd_verification_flags(resolved_at, created_at);

alter table public.im_pwd_verifications enable row level security;
alter table public.im_pwd_verification_flags enable row level security;
drop policy if exists im_pwd_verifications_read on public.im_pwd_verifications;
create policy im_pwd_verifications_read on public.im_pwd_verifications for select
  using (profile_id = public.im_current_profile_id() or public.im_current_profile_role() = 'admin');
drop policy if exists im_pwd_flags_admin_read on public.im_pwd_verification_flags;
create policy im_pwd_flags_admin_read on public.im_pwd_verification_flags for select
  using (public.im_current_profile_role() = 'admin');
revoke insert, update, delete, truncate on public.im_pwd_verifications from anon, authenticated;
revoke insert, update, delete, truncate on public.im_pwd_verification_flags from anon, authenticated;

-- Order lines record which verification earned a PWD discount (0015 column).
alter table public.im_order_items
  drop constraint if exists im_order_items_verification_fk;
alter table public.im_order_items
  add constraint im_order_items_verification_fk
  foreign key (verification_id) references public.im_pwd_verifications(id) on delete set null;

-- ---------------------------------------------------------------------------
-- "Verified" — one definition for badges, selling and discounts
-- ---------------------------------------------------------------------------
create or replace view public.im_verified_pwd
with (security_invoker = false) as
select distinct on (v.profile_id)
  v.profile_id,
  v.id as verification_id,
  v.method,
  v.expires_on,
  v.id_number_last4,
  v.reviewed_at
from public.im_pwd_verifications v
where v.status = 'approved'
  and (v.expires_on is null or v.expires_on >= current_date)
order by v.profile_id, v.reviewed_at desc nulls last, v.id desc;
-- Service role only: no grant to anon/authenticated.
revoke all on public.im_verified_pwd from anon, authenticated;

alter table public.im_profiles
  add column if not exists pwd_grace_until timestamptz;

-- Existing sellers keep selling during the grace period while AVRC reviews
-- them; nobody is silently auto-verified.
update public.im_profiles
   set pwd_grace_until = now() + make_interval(days => public.im_setting_int('seller_verification_grace_days', 30))
 where role = 'seller' and pwd_grace_until is null;

create or replace function public.im_seller_can_sell(p_profile_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $fn$
  select exists (select 1 from public.im_verified_pwd vp where vp.profile_id = p_profile_id)
      or exists (select 1 from public.im_profiles p
                  where p.id = p_profile_id and p.pwd_grace_until is not null and p.pwd_grace_until > now());
$fn$;
revoke all on function public.im_seller_can_sell(bigint) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Storefront: only sellers who may sell; carry the verified badge.
-- ---------------------------------------------------------------------------
drop function if exists public.im_search_products(text, text, numeric, numeric, numeric, text[], bigint, text, integer, integer);
drop function if exists public.im_suggest_products(text, integer);
drop view if exists public.im_storefront_products;

create view public.im_storefront_products
with (security_invoker = false) as
select
  p.id,
  p.seller_id,
  s.name                                   as seller_name,
  p.title,
  p.category,
  p.base_price,
  fs.discount_percent                      as sale_percent,
  fs.ends_at                               as sale_ends_at,
  case when fs.discount_percent is null then p.base_price
       else round(p.base_price * (1 - fs.discount_percent / 100.0), 2) end as effective_price,
  p.rating_avg,
  p.rating_count,
  p.sold_count,
  p.stock_total,
  p.is_featured,
  p.adaptive_tags,
  p.image                                  as placeholder,
  img.url                                  as thumb,
  p.created_at,
  p.search_tsv,
  exists (select 1 from public.im_verified_pwd vp where vp.profile_id = p.seller_id) as seller_verified
from public.im_products p
join public.im_profiles s on s.id = p.seller_id and s.account_status = 'active'
left join lateral (
  select f.discount_percent, f.ends_at
    from public.im_flash_sales f
   where f.product_id = p.id and now() between f.starts_at and f.ends_at
   order by f.starts_at desc
   limit 1
) fs on true
left join lateral (
  select i.url from public.im_product_images i where i.product_id = p.id order by i.position limit 1
) img on true
where p.status = 'approved'
  -- Same rule as im_seller_can_sell(), inlined: a view checks EXECUTE on any
  -- function it calls as the QUERYING role, and that function is not granted
  -- to clients. Sub-selects on im_verified_pwd run as the view owner.
  and (
    exists (select 1 from public.im_verified_pwd vp where vp.profile_id = p.seller_id)
    or (s.pwd_grace_until is not null and s.pwd_grace_until > now())
  );

comment on view public.im_storefront_products is
  'Approved listings from active sellers who may sell (verified PWD, or in their grace period), with stats, the running sale, first photo and the verified badge. Public data only.';
grant select on public.im_storefront_products to anon, authenticated;

create or replace function public.im_search_products(
  p_q        text,
  p_category text    default null,
  p_min      numeric default null,
  p_max      numeric default null,
  p_rating   numeric default null,
  p_tags     text[]  default null,
  p_seller   bigint  default null,
  p_sort     text    default 'relevance',
  p_limit    integer default 24,
  p_offset   integer default 0,
  p_verified boolean default null
)
returns table (
  id bigint, seller_id bigint, seller_name text, title text, category text,
  base_price numeric, sale_percent numeric, sale_ends_at timestamptz, effective_price numeric,
  rating_avg numeric, rating_count integer, sold_count integer, stock_total integer,
  is_featured boolean, adaptive_tags text[], placeholder text, thumb text,
  created_at timestamptz, seller_verified boolean, rank real, total_count bigint
)
language sql
stable
security definer
set search_path = ''
as $fn$
  with q as (
    select nullif(trim(coalesce(p_q, '')), '') as text
  ),
  hits as (
    select sp.*,
           case
             when (select text from q) is null then 0::real
             else ts_rank(sp.search_tsv, websearch_to_tsquery('simple', (select text from q)))
                  + extensions.word_similarity(lower((select text from q)), lower(sp.title))
           end as rank
      from public.im_storefront_products sp
     where ((select text from q) is null
            or sp.search_tsv @@ websearch_to_tsquery('simple', (select text from q))
            or extensions.word_similarity(lower((select text from q)), lower(sp.title)) > 0.45
            or lower(sp.title) like '%' || lower((select text from q)) || '%')
       and (p_category is null or sp.category = p_category)
       and (p_min is null or sp.effective_price >= p_min)
       and (p_max is null or sp.effective_price <= p_max)
       and (p_rating is null or sp.rating_avg >= p_rating)
       and (p_tags is null or sp.adaptive_tags @> p_tags)
       and (p_seller is null or sp.seller_id = p_seller)
       and (p_verified is null or sp.seller_verified = p_verified)
  )
  select h.id, h.seller_id, h.seller_name, h.title, h.category, h.base_price, h.sale_percent,
         h.sale_ends_at, h.effective_price, h.rating_avg, h.rating_count, h.sold_count,
         h.stock_total, h.is_featured, h.adaptive_tags, h.placeholder, h.thumb, h.created_at,
         h.seller_verified, h.rank, count(*) over () as total_count
    from hits h
   order by
     case when p_sort = 'price_asc'  then h.effective_price end asc nulls last,
     case when p_sort = 'price_desc' then h.effective_price end desc nulls last,
     case when p_sort = 'top_sales'  then h.sold_count end desc nulls last,
     case when p_sort = 'rating'     then h.rating_avg end desc nulls last,
     case when p_sort = 'relevance'  then h.rank end desc nulls last,
     h.created_at desc,
     h.id desc
   limit greatest(1, least(coalesce(p_limit, 24), 60))
  offset greatest(0, coalesce(p_offset, 0));
$fn$;
revoke all on function public.im_search_products(text, text, numeric, numeric, numeric, text[], bigint, text, integer, integer, boolean)
  from public, anon, authenticated;

create or replace function public.im_suggest_products(p_q text, p_limit integer default 6)
returns table (id bigint, title text, category text, thumb text, placeholder text,
               base_price numeric, sale_percent numeric, effective_price numeric, score real)
language sql
stable
security definer
set search_path = ''
as $fn$
  select sp.id, sp.title, sp.category, sp.thumb, sp.placeholder, sp.base_price, sp.sale_percent,
         sp.effective_price,
         greatest(extensions.word_similarity(lower(p_q), lower(sp.title)),
                  case when lower(sp.title) like lower(p_q) || '%' then 1
                       when lower(sp.title) like '%' || lower(p_q) || '%' then 0.6
                       else 0 end)::real as score
    from public.im_storefront_products sp
   where length(trim(coalesce(p_q, ''))) >= 2
     and (extensions.word_similarity(lower(p_q), lower(sp.title)) > 0.45
          or lower(sp.title) like '%' || lower(p_q) || '%'
          or sp.search_tsv @@ websearch_to_tsquery('simple', p_q))
   order by score desc, sp.sold_count desc, sp.id
   limit greatest(1, least(coalesce(p_limit, 6), 12));
$fn$;
revoke all on function public.im_suggest_products(text, integer) from public, anon, authenticated;

