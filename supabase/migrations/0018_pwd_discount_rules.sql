-- InclusiveMarket — PWD discount rules (configuration, not code).
--
-- Client decision (§2.5): build the PWD discount, gated on verification,
-- configurable, and OFF until a lawyer confirms which categories each rule
-- covers. The legal landscape the rules must be able to express:
--   * RA 10754 — 20% off plus VAT exemption, only on listed goods/services
--     (medicines, medical/dental, restaurants, hotels, recreation, transport,
--     funeral). Most InclusiveMarket categories are NOT on that list.
--   * DTI-DA Joint Memorandum Circular 01-2022 — 5% on basic necessities and
--     prime commodities bought online/by phone, on up to ₱1,300 of purchases
--     per week.
--   * A voluntary seller or platform PWD promotion — always allowed.
--
-- So the lawyer's answer becomes rows here, not a code change. The database
-- enforces what can be enforced:
--   * every rule is created DISABLED, and cannot be enabled without a recorded
--     legal sign-off (who, when, note);
--   * a statutory rule is exactly 20%; a BNPC rule is exactly 5% with a weekly
--     purchase cap; a rule targets exactly one category OR one product;
--   * at most one enabled rule per category and per product.
-- The pricing engine (lib/pricing) applies it: base → flash sale → PWD rule →
-- caps, only for buyers with an approved, unexpired verification (0017).
--
-- No rows are seeded: nothing is discounted until an admin creates a rule,
-- records the sign-off, and enables it.
--
-- Rollback: supabase/rollback/0018_down.sql

begin;

create table if not exists public.im_discount_rules (
  id                  bigint generated by default as identity primary key,
  name                text not null check (length(trim(name)) >= 3),
  rule_type           text not null check (rule_type in ('statutory_20', 'bnpc_5', 'voluntary')),
  rate_percent        numeric(5,2) not null check (rate_percent > 0 and rate_percent <= 50),
  vat_exempt          boolean not null default false,
  weekly_purchase_cap numeric(12,2) check (weekly_purchase_cap is null or weekly_purchase_cap > 0),
  category_id         text references public.im_categories(id) on delete cascade,
  product_id          bigint references public.im_products(id) on delete cascade,
  funded_by           text not null default 'seller' check (funded_by in ('seller', 'platform')),
  legal_basis         text not null check (length(trim(legal_basis)) >= 3),
  enabled             boolean not null default false,
  legal_signoff_by    bigint references public.im_profiles(id) on delete set null,
  legal_signoff_at    timestamptz,
  legal_signoff_note  text,
  created_by          bigint references public.im_profiles(id) on delete set null,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  constraint im_discount_rules_one_target
    check ((category_id is not null) <> (product_id is not null)),
  constraint im_discount_rules_statutory_shape
    check (rule_type <> 'statutory_20' or rate_percent = 20),
  constraint im_discount_rules_bnpc_shape
    check (rule_type <> 'bnpc_5' or (rate_percent = 5 and weekly_purchase_cap is not null and not vat_exempt)),
  constraint im_discount_rules_vat_only_statutory
    check (not vat_exempt or rule_type = 'statutory_20'),
  constraint im_discount_rules_signoff_before_enable
    check (not enabled or (legal_signoff_at is not null and legal_signoff_by is not null
                           and length(trim(coalesce(legal_signoff_note, ''))) >= 5))
);

create unique index if not exists idx_im_discount_rules_category_enabled
  on public.im_discount_rules(category_id) where enabled and category_id is not null;
create unique index if not exists idx_im_discount_rules_product_enabled
  on public.im_discount_rules(product_id) where enabled and product_id is not null;

alter table public.im_discount_rules enable row level security;
drop policy if exists im_discount_rules_admin_read on public.im_discount_rules;
create policy im_discount_rules_admin_read on public.im_discount_rules for select
  using (public.im_current_profile_role() = 'admin');
revoke insert, update, delete, truncate on public.im_discount_rules from anon, authenticated;

-- Order lines name the rule that discounted them (0015 column).
alter table public.im_order_items drop constraint if exists im_order_items_pwd_rule_fk;
alter table public.im_order_items
  add constraint im_order_items_pwd_rule_fk
  foreign key (pwd_rule_id) references public.im_discount_rules(id) on delete set null;

-- ---------------------------------------------------------------------------
-- Weekly use of each rule by one buyer: pesos of purchases that already
-- earned the discount this week (Philippine time, weeks start Monday), on
-- orders that were not cancelled. The BNPC cap is checked against this.
-- ---------------------------------------------------------------------------
create or replace function public.im_pwd_weekly_usage(p_buyer bigint)
returns table (rule_id bigint, used numeric)
language sql
stable
security definer
set search_path = ''
as $fn$
  select oi.pwd_rule_id, coalesce(sum(oi.pwd_eligible_amount), 0)
    from public.im_order_items oi
    join public.im_orders o on o.id = oi.order_id
   where o.buyer_id = p_buyer
     and oi.pwd_rule_id is not null
     and o.order_status <> 'cancelled'
     and not (o.payment_provider = 'paymongo' and o.payment_status = 'failed')
     and o.created_at >= (date_trunc('week', now() at time zone 'Asia/Manila') at time zone 'Asia/Manila')
   group by oi.pwd_rule_id;
$fn$;
revoke all on function public.im_pwd_weekly_usage(bigint) from public, anon, authenticated;

commit;
